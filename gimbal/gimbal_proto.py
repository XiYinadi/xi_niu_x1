#!/usr/bin/env python3
"""二维云台 UART 帧的**纯函数层** —— 不 import termios/tty,因此本机(Windows)可单测。

分层理由与 `motor_control.py` / `laser_odom_core.py` 同一套路(本项目的既定纪律):

    gimbal_proto.py     ← 纯编码。不碰串口,可单测。**只准 import struct**
    gimbal_proc.py      ← 独立进程,持有 /dev/ttyHS*,唯一允许 import termios 的地方
    gimbal_test.py      ← 离线测试,喂黄金向量进去断言逐字节相等

⚠️⚠️ **这个文件绝不能 import termios / tty / os** —— Windows 上 `import tty`
    直接 ModuleNotFoundError,整个离线测试当场死掉。串口那一层只准出现在
    `gimbal_proc.py`。

==========================================================================
协议(两个独立出处,**都不在本仓库里** —— 所以下面逐字留档)
==========================================================================

  【发端】参考实现 ESP32-S3 `main/hello_world_main.c:241-268
          k230_gimbal_send_frame()`
  【收端】STM32 `hardware/us2/usart2.c:69-114`(解析) + `main.c:328-342`(转速换算)

    6 字节:  0xAA | dxH dxL | dyH dyL | SUM
    dx/dy :  signed int16, **大端**,二进制补码
    SUM   :  (dxH + dxL + dyH + dyL) & 0xFF   ← 算术累加和,**不是 XOR、不是 CRC**
    UART  :  115200 / 8-N-1 / 无流控 / 无转义 / 单向 / 无 ACK

⚠️⚠️ **`0xAA` 是「速度帧」,不是「位置帧」。** 收端把它当**速度**用:

    steps/s = |value| * 80            (SPEED_SCALE)
    钳到 20000                        (MAX_STEPS_PER_SEC)⇒ **|value| ≥ 250 就饱和**
    |value| <= 5                      → 0,**停车并释放电机**(INPUT_DEAD_ZONE)
    正数 → DIR=0(CW);负数 → DIR=1(CCW)

  于是:
    * `(0,0)` = **速度 0 = 停**,**不是**「角度回中」。回中只有 `0xBB cmd=1/2` 能做。
    * **速度是锁存的,收端没有超时保护** —— 「发完 dx=100 不发新帧,云台会**一直转
      下去**」。⇒ 发送侧必须(a)周期性发,(b)**要停就必须显式发 (0,0)**。
      ⚠️ 这条推翻了本项目早先「断链就停发 ⇒ 保持不动」的写法:**停发 = 一直转**。
      见 `gimbal_proc.py` 的 `_step`。
    * **收端没有加减速斜坡** —— 「直接发 0 → 8000 是瞬间跳变,会**丢步/堵转**」。
      ⇒ 斜坡必须由**发送侧**做,见本模块的 `slew_toward()`。

  值域:协议本身是 **int16 全域**。本实现**自己选** ±100 作满量程(`CMD_MIN/CMD_MAX`,
  100 → 8000 steps/s)—— 那是**我们的标度,不是协议上限**。早期注释把它写成
  「协议值域」是错的,别改回去。

参考实现的五行(逐字):

    f[0] = 0xAA;
    f[1] = (dx >> 8) & 0xFF;
    f[2] = dx & 0xFF;
    f[3] = (dy >> 8) & 0xFF;
    f[4] = dy & 0xFF;
    f[5] = (f[1] + f[2] + f[3] + f[4]) & 0xFF;

本模块用 `struct.pack('>hh', dx, dy)` 实现,与上面那五行**逐字节相同**
(2026-09-27 本机核对:12 个用例含 int16 两端 0 处不符;值域 [-100,100]²
 全部 40401 组往返 + 校验和 0 处不符)。

⚠️ `dx/dy` 在参考实现里叫 `s_gimbal_dx_deg`(hello_world_main.c:88-89)——
   **这名字骗人**,它不是角度,是摇杆的 cmd100 归一化量。

--------------------------------------------------------------------------
⚠️⚠️ 校验和对**字节序完全瞎** —— 这条决定了测试怎么写
--------------------------------------------------------------------------
SUM 是四个字节的普通和,与顺序无关。所以:

    大端  AA FF9C 0000 9B   →  SUM=9B  →  接收端按大端解出 dx = -100    ✅
    小端  AA 9CFF 0000 9B   →  SUM=9B  →  接收端按大端解出 dx = -25345  ❌

**小端实现、dx/dy 写反,都照样通过校验。**
单比特翻转检出率是 100%(2026-09-27 本机 1,292,832 用例)——
即它**对付位错完美、对付顺序错全盲**。

⇒ `gimbal_test.py` 里**绝不能**断言「校验和正确」当通过条件。
  必须断言**逐字节相等的固定向量**。

--------------------------------------------------------------------------
回调里的危险字节(决定串口必须 raw)
--------------------------------------------------------------------------
值域内 40401 种帧里,payload 命中这些字节的比例:
    0x0A 1.46% / 0x0D 1.45% / 0x11 1.44% / 0x13 1.43%
⇒ 拨几十次摇杆就撞上一次。非 raw 时驱动会:把 0x0A 改写成 0D 0A(帧长 6→7,
静默移位)、把 0x11/0x13 当流控吞掉(静默少字节)。见 gimbal_proc.py。

--------------------------------------------------------------------------
⚠️⚠️ `0xAA` **会**出现在数据字节里 —— 本协议没有帧同步能力
--------------------------------------------------------------------------
`pack('>h')` 的高字节只能是 0x00(正)或 0xFF(负);低字节是:
    正值 n∈[0,100]   → n            → [0x00, 0x64]
    负值 n∈[-100,-1] → n & 0xFF     → [0x9C, 0xFF]

空隙是 [0x65, 0x9B](= 101..155),**但 0xAA = 170 不在空隙里** —— 它在负值段,
对应 `-86 & 0xFF`。实测(2026-09-27):值域 [-100,100]² 的 40401 组帧里,
**401 组含一个假帧头,全部来自 `dx == -86` 或 `dy == -86`**,如:

    (-20, -86) → AA FF EC FF AA 94        ← byte4 的 AA 是数据,不是帧头

⚠️ 2026-09-27 之前这里写的是「0xAA 在值域内不可达」—— **那是错的**
   (把 0x9C=156 当成了大于 0xAA=170)。`gimbal_test.py::test_no_header_collision`
   现在逐组穷举断言**真实**性质,别再把结论改回去。

**后果(这条比 0xAA 重码本身更要紧)**:
  * **协议没有帧头同步兜底** —— 接收端不能靠「扫到 0xAA 就当帧头」重新对齐,
    数据字节会被当成帧头。
  * 所以 `gimbal_proc.py` 里**短写必须补齐余下字节**:一次短写把接收端的解析
    相位永久推移,而接收端**没有自愈手段**(它只能靠校验和把那 0xAA 当坏帧丢掉,
    丢掉之后仍停在错相位上 —— 因为长度是定长的 6 字节,丢不掉)。
"""

import struct

#: 帧头。值域内数据字节不可能等于它(见模块 docstring),所以是个真帧头。
HEADER = 0xAA

#: 一帧固定 6 字节。**没有转义、没有变长** —— 短写会永久推移接收端的解析相位。
FRAME_LEN = 6

#: **本实现选定的**满量程(不是角度,也不是协议上限)。
#: 协议是 int16 全域、|value| ≥ 250 饱和(=20000 steps/s)。选 100 是因为 100 已经
#: 是 8000 steps/s,再高只是更早堵转;要放开就改这里(值域本身是合法的)。
CMD_MIN = -100
CMD_MAX = 100

_FRAME_STRUCT = struct.Struct(">hh")


def clamp_cmd100(v):
    """把任意数钳进协议值域 [-100, 100],返回 `int`。

    镜像 `pwm_proc._recv_latest` 的思路:**别信网络来的数**。前端可能因为
    丢包/改版/别的客户端塞进来一个 5000,直接编码进 int16 也「合法」
    (`pack('>hh')` 只要求 int16),但接收端的云台不知道该怎么理解它。
    在**唯一入口**钳一次,后面就都是干净的。

    ⚠️ 钳位而不是抛异常:这是给实时链路用的,一个坏包不该让循环停摆。
       真正需要响亮失败的地方在 `encode_frame`(见下)。

    四类输入的约定(都有用例盯着):
        正常数    → 钳到 [-100,100],向零取整
        ±inf      → 钳到 ±100(**不是**回 0:它比 100 还大,回 0 等于把
                    「推到底」悄悄改成「零速停车」,方向正好相反)
        NaN       → 0(无序,没有正确的钳法)
        非数(字符串/None/容器) → 0

    ⚠️ `inf` 不能走 `int(float(v))` —— `int(float('inf'))` 抛 **OverflowError**,
       它不在 (TypeError, ValueError) 里。2026-09-27 被 `gimbal_test.test_clamp`
       抓到:实时链路上一个 inf 包就能让进程崩掉。所以下面先比大小、再取整。
    """
    try:
        f = float(v)
    except (TypeError, ValueError):
        return 0
    if f != f:                  # NaN:唯一一种无法排序的值
        return 0
    if f <= CMD_MIN:
        return CMD_MIN
    if f >= CMD_MAX:
        return CMD_MAX
    return int(f)


def slew_toward(cur, target, rate_per_s, dt):
    """朝 `target` 走**一步**,每步的变化量不超过 `rate_per_s * dt`。返回 `int`。

    为什么必须存在:**收端没有加减速斜坡**(见模块 docstring)。摇杆从 0 推到满,
    我们原来那一帧就把它变成 `|100| * 80 = 8000 steps/s` 的阶跃 —— 协议原文点 2 明写
    这种跳变会「**丢步/堵转**」,而堵转的步进电机在现场看就是「**推摇杆没反应**」。
    协议把斜坡的责任划给了发送侧(「斜坡要在你这边做,比如每 20ms 让值变化不超过 ±5」)。

    参数:
        cur/target : 单位与协议一致(本实现是 ±100)。按 `int` 处理。
        rate_per_s : 变化速率,**单位/秒**。`<= 0` ⇒ **直通**(回到没有斜坡的行为,
                     留给 A/B 对照用)。协议建议值 = 5 / 0.02 = **250**。
        dt         : 距上一次的秒数。

    ⚠️⚠️ **`dt` 的钳位是调用方的责任,不是这里的。** 循环若卡了 1 秒,`dt=1.0` 会算出
       `max_delta = 250` ⇒ **一帧跳满** —— 正好把斜坡整个绕过去,而且是在最需要它的
       那一刻(卡顿之后)。`gimbal_proc._step` 里钳到 `2 * period`。
       本函数不替调用方钳:它是个纯函数,不知道什么算「太长」。

    ⚠️ 别把它写成「每帧固定 ±N」的版本。那样帧率一改,**斜坡速率跟着变** ——
       两个本该独立的旋钮被焊在一起,而且是那种「调了 A 发现 B 也变了」的坑。

    到位的行为:`|target - cur| <= max_delta` 时**精确返回 target**,
    不是「再走一步然后靠下一步走回来」—— 后者会在目标附近**振荡**(永远差 1)。
    """
    cur, target = int(cur), int(target)
    if rate_per_s <= 0:
        return target                       # 斜坡关闭:直通
    if dt <= 0:
        return cur                          # 没时间流逝就不该动
    step = int(rate_per_s * dt)
    if step <= 0:
        return cur                          # 速率太低、这一帧还不够走 1 个单位
    if target > cur:
        return min(target, cur + step)
    if target < cur:
        return max(target, cur - step)
    return target


def encode_frame(dx, dy):
    """`(dx, dy)` → 6 字节帧。**这是与 C 参考实现逐字节相同的那条式子。**

    ⚠️ 与 `clamp_cmd100` 的分工:本函数**不钳位**。它只负责「int16 → 线上字节」,
       超出 int16 时**响亮地抛 ValueError**(而不是静默截断/回绕 —— 回绕会把
       「往右到底」变成「往左到底」,是那种不说谎的失败)。值域钳制是调用方
       (进程的 UDP 入口)用 `clamp_cmd100` 做的。

       这样分工的理由:编码层越纯越好测。一旦它自己钳位,黄金向量就只能证明
       「钳位后的值编对了」,证明不了协议本身。
    """
    try:
        body = _FRAME_STRUCT.pack(int(dx), int(dy))
    except struct.error as e:
        raise ValueError(
            f"dx={dx!r} dy={dy!r} 超出 int16 —— 编码层只保证 int16。"
            f"用 clamp_cmd100() 在入口钳一次(本实现的满量程是 ±100)。({e})") from e

    # body 正好是 byte1..byte4;SUM 是它们的普通和,与顺序无关(见模块 docstring)。
    return bytes([HEADER]) + body + bytes([sum(body) & 0xFF])


def decode_frame(buf):
    """6 字节 → `(dx, dy)`。**不负责校验** —— 见下。

    给三处用:
      * `gimbal_test.py` 的往返测试
      * 板端**回环测试**(短接 pin29↔pin16,把发出去的读回来比对)
      * 板端**被动监听**(抓线上真实字节流,验相位)

    ⚠️ 返回 `None` 表示「这 6 个字节不是一帧」—— 判据是**帧头** + **校验和**。
       但请注意:校验和只能查出位错,**查不出字节序错**(模块 docstring 里那张表)。
       所以这个函数判「像不像一帧」够用,判「编码对不对」**不够用** ——
       后者只有黄金向量能判。

    ⚠️ 长度不对也返回 None 而不是抛异常:被动监听时手上是一整段流,
       调用方需要能拿任意 6 字节窗口来试。
    """
    if buf is None or len(buf) != FRAME_LEN:
        return None
    if buf[0] != HEADER:
        return None
    body = buf[1:5]
    if (sum(body) & 0xFF) != buf[5]:
        return None
    return _FRAME_STRUCT.unpack(body)


def frame_hex(frame):
    """`b'\\xaa\\xff\\x9c\\x00\\x00\\x9b'` → `'AA FF 9C 00 00 9B'`。

    日志和测试用例里到处要用,单独拎出来免得各处手写格式化手滑。
    """
    return " ".join(f"{b:02X}" for b in frame)
