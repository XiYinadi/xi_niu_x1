const fs=require('fs'),vm=require('vm'),assert=require('assert');
const js=fs.readFileSync(__dirname+'/autonomy.js','utf8'),html=fs.readFileSync(__dirname+'/slam_viz.py','utf8');
const ids=new Set([...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]));
const els={},events={},sent=[];
const el=id=>els[id]||(els[id]={value:'',hidden:false,disabled:false,textContent:'',handlers:{},addEventListener(k,f){this.handlers[k]=f;}});
for(const m of js.matchAll(/el\('([^']+)'\)/g))assert(ids.has(m[1]),m[1]);
const socket={connected:true,on:(k,f)=>events[k]=f,emit:(k,v)=>sent.push({k,v})};
vm.runInNewContext(js,{document:{getElementById:el},socket,confirm:()=>true,Math});
const ready={localized:true,navigator_ready:true,running:true,busy:false,mode:'mapping',patrols:[{name:'test'}],autonomy:{active:false,camera_ready:true,message:'ready'}};
events.navigation_state({...ready,calibration_error:'unmeasured'});
assert(el('auto-explore').disabled);el('auto-explore').handlers.click();assert.equal(sent.length,0);
events.navigation_state(ready);assert(!el('auto-explore').disabled);assert(el('auto-patrol').disabled);
el('nav-name').value='map_a';el('auto-explore').handlers.click();assert.equal(sent.at(-1).v.action,'explore_start');
assert.equal(sent.at(-1).v.name,'map_a');
events.navigation_state({...ready,mode:'localization',autonomy:{...ready.autonomy,active:true,kind:'patrol'}});
assert(el('auto-explore').disabled);assert(el('auto-patrol').disabled);
events.autonomy_alert({reason:'<script>bad</script>'});assert.equal(el('autonomy-alert-message').textContent,'⚠ 已停车，等待人工复核：<script>bad</script>');
assert(!el('autonomy-alert').hidden);
el('auto-stop').handlers.click();assert.equal(sent.at(-1).v.action,'mission_stop');
socket.connected=false;events.disconnect();assert(el('auto-explore').disabled);assert(el('auto-patrol').disabled);
assert(!sent.some(x=>x.k==='motor_control'));
console.log('Autonomy UI PASS: calibration gates, mode gates, alert text, stop, disconnect; never arms');
